"""Replay actual joint samples over every claimed continuous hold interval."""
import argparse,hashlib,json,sys
from pathlib import Path


def audit(directory):
    folder=Path(directory);snapshot=folder/'source_snapshot'
    sys.path.insert(0,str(snapshot/'src'))
    from simpeople.core.gestures import measure
    events=[json.loads(line) for line in (folder/'events.jsonl').open()]
    starts={(e['agent'],int(e['native_task_id'])):e for e in events if e['kind']=='native_gesture_started'}
    bindings={(e['actor_id'],e['native_task_id']):e for e in events if e['kind']=='native_task_bound' and e.get('native_task_id') is not None}
    holds=[e for e in events if e['kind']=='gesture_hold_completed']
    samples={};actual_bases={}
    for line in (folder/'trajectories.jsonl').open():
        row=json.loads(line);samples.setdefault(row.get('task_id'),[]).append(row)
        if row.get('action')=='mb_stand':
            key=(row['actor_id'],row.get('native_task_id'));actual_bases[key]=actual_bases.get(key,0)+1
    rows=[];errors=[]
    for hold in holds:
        tid=hold['task_id'];task_rows=samples.get(tid,[])
        # The completed event is generated by Engine.step at the same sim instant
        # as the captured pose. Replay from the recorded native start baseline.
        bound=next((b for b in bindings.values() if b['task_id']==tid),None)
        start=next((e for e in starts.values() if e['native_task_id']==(bound or {}).get('native_task_id') and e['agent'].split('/Actors/')[-1].split('/')[0]==hold['actor_id']),None)
        if start is None:errors.append({'task_id':tid,'reason':'native baseline missing'});continue
        begin=hold['sim_time']-hold['hold_sim_s']
        selected=[r for r in task_rows if begin-1e-7<=r['observation_sim_time']<=hold['sim_time']+1e-7]
        # Host frames use the same absolute simulation time as the journal.
        values=[measure(start['action'],start.get('hand'),start['target_m'],start['baseline'],r) for r in selected]
        complete=bool(values) and len(values)>=round(hold['hold_sim_s']*30) and all(v['aligned'] for v in values)
        if not complete:errors.append({'task_id':tid,'reason':'claimed hold not supported by continuous actual joint samples','samples':len(values)})
        rows.append({'task_id':tid,'actor_id':hold['actor_id'],'action':start['action'],'hold_sim_s':hold['hold_sim_s'],'samples':len(values),'continuous_hold_verified':complete,
            'maximum_root_displacement_m':max((v['root_displacement_m'] for v in values),default=None),
            'maximum_root_turn_deg':max((v['root_facing_change_deg'] for v in values),default=None),
            'maximum_target_error':max((v.get('hand_error_m',v.get('head_angle_error_deg')) for v in values),default=None),
            'maximum_active_arm_length_deviation':max((v['active_arm_length_max_deviation'] for v in values),default=None)})
    acceptance=json.loads((folder/'gesture_runtime_acceptance.json').read_text())
    base_checks=[]
    for start in starts.values():
        if start.get('base_task_id') is None:continue
        actor=start['agent'].split('/Actors/')[-1].split('/')[0];key=(actor,start['base_task_id'])
        state=next((s for s in acceptance.get('owned_base_states',[]) if s['agent']==start['agent'] and s['native_task_id']==start['base_task_id']),{})
        check={'actor_id':actor,'base_task_id':start['base_task_id'],'actual_native_frames':actual_bases.get(key,0),'ended':state.get('ended',False)}
        check['passed']=check['actual_native_frames']>0 and check['ended'];base_checks.append(check)
        if not check['passed']:errors.append({'reason':'experimental base was not observed running and ended','base':check})
    return {'run_id':folder.name,'passed':bool(rows) and not errors and acceptance['passed'],'holds':rows,'errors':errors,
        'experimental_base_checks':base_checks,
        'runtime_acceptance_passed':acceptance['passed'],
        'measure_source_sha256':hashlib.sha256((snapshot/'src/simpeople/core/gestures.py').read_bytes()).hexdigest(),
        'audit_source_sha256':hashlib.sha256(Path(__file__).read_bytes()).hexdigest(),
        'limits':['joint and root geometry proxies; no force, grasp or whole-body mesh certification','head forward axis comes from the asset bind pose, not eye tracking','each completed hold is replayed at captured simulation times; native release/task checks are separate']}


if __name__=='__main__':
    p=argparse.ArgumentParser();p.add_argument('directory');a=p.parse_args();result=audit(a.directory)
    (Path(a.directory)/'gesture_replay_audit.json').write_text(json.dumps(result,indent=2)+'\n')
    print(json.dumps({'passed':result['passed'],'holds':len(result['holds']),'errors':result['errors']},indent=2))
    if not result['passed']:raise SystemExit(1)
